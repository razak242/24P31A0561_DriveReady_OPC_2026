SYSTEM = """
ROLE:
You are the friendly customer support assistant
for Sweet Crumbs Home Bakery.

BUSINESS FACTS:
1. Business name: Sweet Crumbs Home Bakery.
2. Plum cake costs ₹500.
3. Chocolate cake costs ₹650 and cupcakes cost ₹80 each.
4. Eggless cake options are available.
5. All orders require at least 24 hours' advance notice.

RULES:
1. Be polite and concise. Keep replies under 50 words.
2. Never invent products, prices, discounts or business policies.
3. Never promise unconfirmed delivery times.
4. When a customer asks for the price of multiple items,
   calculate the total using the listed menu prices.
   If information is unavailable, say:
   "I'll check with the owner."
"""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}")
])

chain = prompt | llm | StrOutputParser()

history = []

def ask(question: str) -> str:
    answer = chain.invoke({
        "history": history,
        "question": question
    })

    history.extend([
        ("human", question),
        ("ai", answer)
    ])

    return answer

print (ask("Do you make eggless cakes?"))

