import csv

def run_tests(path="/content/tests.csv"):
    with open(path, "r", encoding="utf-8") as file:
        rows = list(csv.DictReader(file))

    passed = 0

    for row in rows:
        answer = chain.invoke({
            "history": [],
            "question": row["question"]
        })

        expected = row["must_include"].lower()
        success = expected in answer.lower()

        if success:
            passed += 1

        print(
            "PASS" if success else "FAIL",
            "|",
            row["question"],
            "->",
            answer[:100]
        )

    percentage = passed / len(rows) * 100

    print(f"\n{passed}/{len(rows)} passed ({percentage:.0f}%)")

    return passed, percentage

