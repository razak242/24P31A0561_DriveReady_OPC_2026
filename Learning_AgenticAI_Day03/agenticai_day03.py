MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}

def get_price(item: str, quantity: int = 1) -> int:
    """Return the total price of a bakery item."""

    item = item.lower().strip()

    if item not in MENU:
        raise ValueError("Item not found in menu.")

    if quantity <= 0:
        raise ValueError("Quantity must be greater than zero.")

    return MENU[item] * quantity

print(get_price("plum cake"))
print(get_price("cupcake", 6))
print(get_price("chocolate cake", 2))

def check_order_availability(hours_until_order: int) -> bool:
    """Check whether an order meets the 24-hour advance notice requirement."""

    return hours_until_order >= 24

print(check_order_availability(48))
print(check_order_availability(24))
print(check_order_availability(5))















