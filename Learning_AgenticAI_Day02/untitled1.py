MAX_TURNS = 8



def chat(user_text: str) -> str:

    history.append({
        "role": "user",
        "content": user_text
    })

    recent = [history[0]] + history[1:][-MAX_TURNS:]

    try:

        response = client.chat.completions.create(
            model=MODEL,
            messages=recent,
            temperature=0.3
        )

        reply = response.choices[0].message.content

    except RateLimitError:
        reply = "We are a little busy. Please try again in a minute."

    except AuthenticationError:
        reply = "There is an API authentication problem. Please check the setup."

    except APIConnectionError:
        reply = "I cannot reach the server right now. Please try again shortly."

    history.append({
        "role": "assistant",
        "content": reply
    })

    return reply



