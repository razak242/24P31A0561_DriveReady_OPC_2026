from typing import Literal
from pydantic import BaseModel, Field
from langchain.tools import tool

MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}

HOURS = {
    "monday": "9 am to 8 pm",
    "tuesday": "9 am to 8 pm",
    "wednesday": "9 am to 8 pm",
    "thursday": "9 am to 8 pm",
    "friday": "9 am to 8 pm",
    "saturday": "9 am to 8 pm",
    "sunday": "10 am to 6 pm"
}

class Order(BaseModel):
    """A cake order taken from a customer's chat message."""

    name: str = Field(description="Customer's first name")

    item: Literal[
        "plum cake",
        "chocolate cake",
        "cupcake"
    ] = Field(description="Menu item")

    qty: int = Field(description="How many", ge=1)

    date: str = Field(
        description="Pickup date as the customer said it"
    )

    eggless: bool = Field(
        description="True if the customer asked for eggless"
    )

@tool
def get_price(item: str, qty: int = 1) -> str:
    """Get the total price in rupees for a quantity of one menu item.

    Args:
        item: Menu item, e.g. "plum cake", "chocolate cake" or "cupcake"
        qty: How many the customer wants
    """
    price = MENU.get(item.lower().strip())

    if price is None:
        return f"'{item}' is not on the menu. We have: {', '.join(MENU)}."

    return f"{qty} x {item} = Rs {price * qty}"


@tool
def is_open(day: str) -> str:
    """Check the bakery's opening hours for a day of the week."""

    hours = HOURS.get(day.lower().strip())

    return (
        f"Open {hours} on {day}."
        if hours
        else f"'{day}' is not a day of the week."
    )


@tool
def log_order(
    name: str,
    item: str,
    qty: int,
    date: str,
    eggless: bool
) -> str:
    """Save a confirmed cake order to the Orders sheet.
    Use only when the customer has given their name,
    item, quantity and pickup date.
    """

    try:
        order = Order(
            name=name,
            item=item.lower().strip(),
            qty=qty,
            date=date,
            eggless=eggless
        )

    except Exception as e:
        return f"Could not save the order: {e}. Ask the customer to correct it."

    total = MENU[order.item] * order.qty

    ws.append_row([
        order.name,
        order.item,
        order.qty,
        order.date,
        "yes" if order.eggless else "no",
        total
    ])

    return (
        f"Saved: {order.qty} x {order.item} for "
        f"{order.name} on {order.date}, Rs {total}."
    )

from langchain.agents import create_agent

SYSTEM = """ROLE: You are the friendly order assistant for Sweet Crumbs Home Bakery.

FACTS: Orders need 24 hours' notice. All cakes have eggless versions.

RULES:
Always use get_price for prices and is_open for timings; never guess them.
Before log_order, make sure you have name, item, quantity and pickup date.
Ask the customer if any required detail is missing.
After saving, read the order back with the total.

FORMAT:
Under 60 words, friendly, English or Telugu matching the customer.
"""

agent = create_agent(
    model=llm,
    tools=[get_price, is_open, log_order],
    system_prompt=SYSTEM
)

history = []
last_result = None

def chat(text: str) -> str:
    global history, last_result

    try:
        last_result = agent.invoke({
            "messages": history + [
                {"role": "user", "content": text}
            ]
        })

        history = last_result["messages"]

        return history[-1].content

    except Exception as e:
        print("Agent error:", e)
        return "Sorry, I'm a little busy. Please try again in a minute."

print(chat("Are you open on Sunday? How much are 2 chocolate cakes?"))

